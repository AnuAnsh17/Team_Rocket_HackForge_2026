"""Declarative base, naming conventions and shared column helpers.

Conventions applied to every table in the schema:

* Primary keys are UUIDs (``uuid_generate_v4`` is NOT required; Python generates
  the value with ``uuid4`` so the application never depends on a database
  extension). Public ids are therefore opaque and non-enumerable.
* Every enum-valued column is ``varchar`` plus an explicit ``CHECK`` constraint
  rather than a PostgreSQL native enum. Adding a value later is then an ordinary
  migration instead of an ``ALTER TYPE`` on a live table.
* Money is ``NUMERIC(20, 4)``, never floating point.
* Timestamps are timezone-aware and stored in UTC.
* Constraint names are deterministic (``ck_``, ``uq_``, ``ix_``, ``fk_``) so
  migrations and error messages are reviewable.
"""

from __future__ import annotations

import uuid
from collections.abc import Sequence
from datetime import UTC, datetime
from enum import Enum as PyEnum
from typing import Any

from sqlalchemy import CheckConstraint, DateTime, MetaData, Numeric, String, func
from sqlalchemy.dialects.postgresql import UUID as PGUUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

# --- Naming convention ----------------------------------------------------
# Without this, autogenerated constraint names differ between databases and
# Alembic produces unreviewable migrations.
NAMING_CONVENTION: dict[str, str] = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}

# Money precision. 4 decimal places covers currencies with minor units beyond
# 2 (and intermediate aggregation without premature rounding). Rounding rules
# for any specific policy are NOT decided here: no policy has been supplied.
MONEY = Numeric(20, 4)

# Length used by every enum-backed varchar column.
ENUM_LENGTH = 32


class Base(DeclarativeBase):
    """Declarative base for every Proofline table."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)

    def __repr__(self) -> str:  # pragma: no cover - debug convenience
        identifier = getattr(self, "id", None)
        return f"<{type(self).__name__} id={identifier!r}>"

    def as_dict(self) -> dict[str, Any]:  # pragma: no cover - debug convenience
        return {c.name: getattr(self, c.name) for c in self.__table__.columns}


def new_uuid() -> uuid.UUID:
    return uuid.uuid4()


def utcnow() -> datetime:
    """Timezone-aware UTC now. Used for every default and comparison."""
    return datetime.now(UTC)


def uuid_pk() -> Mapped[uuid.UUID]:
    """Standard UUID primary key column."""
    return mapped_column(PGUUID(as_uuid=True), primary_key=True, default=new_uuid)


class UUIDPrimaryKeyMixin:
    id: Mapped[uuid.UUID] = uuid_pk()


class CreatedAtMixin:
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), nullable=False, default=utcnow, server_default=func.now()
    )


class TimestampMixin(CreatedAtMixin):
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=utcnow,
        onupdate=utcnow,
        server_default=func.now(),
    )


def enum_values(enum_cls: type[PyEnum]) -> list[str]:
    """Return the string values of an enum for use in a CHECK constraint."""
    return [str(member.value) for member in enum_cls]


def enum_column(enum_cls: type[PyEnum], *, nullable: bool = False) -> Mapped[str]:
    """A varchar column constrained to the values of ``enum_cls``.

    The CHECK constraint is attached by the owning table via ``in_enum()`` so
    that the constraint name remains explicit per table.
    """
    return mapped_column(String(ENUM_LENGTH), nullable=nullable)


def in_enum(name: str, enum_cls: type[PyEnum]) -> CheckConstraint:
    """Build the CHECK constraint for an enum-valued column.

    Usage in a model::

        __table_args__ = (in_enum("status", ExpenseStatus),)

    which produces::

        CONSTRAINT ck_expenses_status CHECK (status IN ('draft', 'submitted', ...))
    """
    return in_values(name, enum_values(enum_cls))


def in_list(values: Sequence[str]) -> str:
    """Render a SQL ``IN`` list for embedding inside a larger expression.

    Needed where a constraint is more than a single ``IN`` test -- for example the
    policy-assignment scope selector, which combines one ``IN`` test with a
    nullability rule.
    """
    return "(" + ", ".join(f"'{value}'" for value in values) + ")"


def in_values(name: str, values: Sequence[str]) -> CheckConstraint:
    """Build a CHECK constraint asserting a column is one of a fixed set.

    Used for enum-backed columns and for small open sets that are not modelled
    as enums (for example allowance period types).
    """
    return CheckConstraint(f"{name} IN {in_list(values)}", name=name)


def non_negative(name: str) -> CheckConstraint:
    """Build a CHECK constraint asserting a numeric column is >= 0."""
    return CheckConstraint(f"{name} >= 0", name=f"{name}_non_negative")
